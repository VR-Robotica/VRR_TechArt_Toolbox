/*
 * Toolbox > Bake Normals page (UI only).
 *
 * The page edits an FSmoothNormalBakeSettings and hands it to SmoothNormalBaker::Bake (Core_BakeNormals.cpp),
 * which does all the mesh work. This file builds the widgets, keeps the mesh info line current, asks before
 * overwriting existing vertex colors, and shows the result (status line, toast, Content Browser).
 */

#include "Menu_BakeNormals.h"

#include "Core_Common.h"
#include "Engine/Texture2D.h"
#include "MenuWidgets.h"
#include "MeshDescription.h"
#include "Misc/MessageDialog.h"
#include "Misc/PackageName.h"
#include "Widgets/Input/SSegmentedControl.h"
#include "Widgets/Layout/SBox.h"
#include "Widgets/Text/STextBlock.h"

#define LOCTEXT_NAMESPACE "SMenu_BakeNormals"

/** Builds the page: one card per step, top to bottom. */
void SMenu_BakeNormals::Construct(const FArguments& InArgs)
{
	ChildSlot
	[
		VrrMenu::Stack({
			CreateMeshSection(),
			CreateSmoothingSection(),
			CreateMaskSection(),
			CreateEncodingSection(),
			CreateOutputSection(),
			CreateBakeSection(),
		})
	];
}

// LAYOUT
/** Mesh picker, "Use Selected" button and the mesh info line. */
TSharedRef<SWidget> SMenu_BakeNormals::CreateMeshSection()
{
	return VrrMenu::Card(LOCTEXT("MeshHeader", "Source Mesh"), VrrMenu::Rows({
		VrrMenu::Row(LOCTEXT("MeshLabel", "Mesh"),
			VrrMenu::MeshPicker(VrrMenu::EMeshTypes::StaticOrSkeletal,
				[this]() { return Mesh.Get(); },
				[this](UObject* NewMesh) { SetMesh(NewMesh); },
				[this](const FText& Error) { SetStatus(Error, true); })),
		VrrMenu::Note(TAttribute<FText>::CreateSP(this, &SMenu_BakeNormals::GetMeshInfoText)),
	}));
}

/** Weld distance (how close vertices must be to share one smooth normal) and whether to bake every LOD. */
TSharedRef<SWidget> SMenu_BakeNormals::CreateSmoothingSection()
{
	return VrrMenu::HelpCard(LOCTEXT("SmoothingHeader", "Smoothing"), LOCTEXT("SmoothingInfo", "Normals are averaged over every vertex at the same position, ignoring hard edges and UV seams. The mesh's own shading normals are not changed."), VrrMenu::Rows({
		VrrMenu::Row(LOCTEXT("WeldDistance", "Weld distance (cm)"),
			VrrMenu::FloatField(&Settings.WeldDistance, 0.0f, 10.0f, 0.001f),
			LOCTEXT("WeldDistanceTip", "Vertices closer than this count as the same point. Raise it if separate pieces that touch should share one outline")),
		VrrMenu::Row(LOCTEXT("LODs", "LODs"),
			VrrMenu::CheckBox(&Settings.bAllLODs, LOCTEXT("AllLODs", "Bake all LODs"),
				LOCTEXT("AllLODsTip", "Bake every LOD that has its own mesh data. LODs generated by reduction are rebuilt from LOD 0. Texture bakes always use LOD 0"))),
	}));
}

/** Thickness mask options (thinner outlines on tight curves, stored in alpha). */
TSharedRef<SWidget> SMenu_BakeNormals::CreateMaskSection()
{
	const TAttribute<bool> MaskOn = TAttribute<bool>::CreateLambda([this]() { return Settings.bBakeThicknessMask; });

	return VrrMenu::HelpCard(LOCTEXT("MaskHeader", "Thickness Mask"), LOCTEXT("MaskInfo", "Writes an outline width multiplier into alpha: 1 on broad surfaces, lower where the surface curves tightly (nose, lips, eyelids, fingers). Turn on UseThicknessMask in the outline material to use it."), VrrMenu::Rows({
		VrrMenu::Row(LOCTEXT("MaskLabel", "Mask"),
			VrrMenu::CheckBox(&Settings.bBakeThicknessMask, LOCTEXT("BakeMask", "Bake thickness mask into alpha"),
				LOCTEXT("BakeMaskTip", "Replaces the alpha channel (vertex colors or texture) with the curvature-based width mask"))),
		VrrMenu::Row(LOCTEXT("MaskFullRadius", "Full width radius (cm)"),
			VrrMenu::FloatField(&Settings.MaskFullRadius, 0.1f, 100.0f, 0.1f),
			LOCTEXT("MaskFullRadiusTip", "Surfaces that curve more gently than this radius keep the full outline width. Raise it to thin more of the mesh"),
			MaskOn),
		VrrMenu::Row(LOCTEXT("MaskMinimum", "Minimum width"),
			VrrMenu::FloatField(&Settings.MaskMinimum, 0.0f, 1.0f, 0.01f),
			LOCTEXT("MaskMinimumTip", "Width multiplier on the tightest curves (0 hides the outline there, 1 turns the mask off)"),
			MaskOn),
	}));
}

/** Tangent or object space (object is static-mesh only), plus Lock Tangents. */
TSharedRef<SWidget> SMenu_BakeNormals::CreateEncodingSection()
{
	return VrrMenu::Card(LOCTEXT("EncodingHeader", "Encoding"), VrrMenu::Rows({
		VrrMenu::Row(LOCTEXT("Space", "Space"),
			SNew(SSegmentedControl<ESmoothNormalSpace>)
			.Value_Lambda([this]() { return Settings.Space; })
			.OnValueChanged_Lambda([this](ESmoothNormalSpace NewSpace)
			{
				if (NewSpace == ESmoothNormalSpace::Object && IsSkeletal())
				{
					SetStatus(LOCTEXT("ObjectSpaceSkeletal", "Object space doesn't follow skinning. Skeletal meshes use tangent space."), true);
					return;
				}
				Settings.Space = NewSpace;
			})
			+ SSegmentedControl<ESmoothNormalSpace>::Slot(ESmoothNormalSpace::Tangent)
				.Text(LOCTEXT("TangentSpace", "Tangent"))
				.ToolTip(LOCTEXT("TangentSpaceTip", "Relative to each vertex's tangent basis. Follows skinning and rotation. Decode with Transform Vector (Tangent to World)"))
			+ SSegmentedControl<ESmoothNormalSpace>::Slot(ESmoothNormalSpace::Object)
				.Text(LOCTEXT("ObjectSpace", "Object"))
				.ToolTip(LOCTEXT("ObjectSpaceTip", "Mesh local space. Static meshes only. Decode with Transform Vector (Local to World)"))),
		VrrMenu::Row(LOCTEXT("Tangents", "Tangents"),
			VrrMenu::CheckBox(&Settings.bLockTangents, LOCTEXT("LockTangents", "Lock tangents"),
				LOCTEXT("LockTangentsTip", "Tangent-space data only decodes correctly if the GPU's tangents match the ones it was encoded against.\n"
					"This computes the normals and tangents now, the same way the build would, stores them in the mesh,\n"
					"and turns off Recompute Normals/Tangents in the LOD build settings so a rebuild can't change them.")),
			FText::GetEmpty(),
			TAttribute<bool>::CreateLambda([this]() { return Settings.Space == ESmoothNormalSpace::Tangent; })),
	}));
}

/** Target (vertex colors or texture) and the options of each: keep alpha, or UV channel/size/padding/folder/name. */
TSharedRef<SWidget> SMenu_BakeNormals::CreateOutputSection()
{
	auto TextureOnly = [this]() { return Settings.Target == ESmoothNormalTarget::Texture ? EVisibility::Visible : EVisibility::Collapsed; };
	auto VertexColorOnly = [this]() { return Settings.Target == ESmoothNormalTarget::VertexColor ? EVisibility::Visible : EVisibility::Collapsed; };
	auto OnlyWhen = [](auto Visibility, const TSharedRef<SWidget>& Widget) -> TSharedRef<SWidget>
	{
		return SNew(SBox).Visibility_Lambda(Visibility)[ Widget ];
	};

	return VrrMenu::Card(LOCTEXT("OutputHeader", "Output"), VrrMenu::Rows({
		VrrMenu::Row(LOCTEXT("BakeInto", "Bake into"),
			SNew(SSegmentedControl<ESmoothNormalTarget>)
			.Value_Lambda([this]() { return Settings.Target; })
			.OnValueChanged_Lambda([this](ESmoothNormalTarget NewTarget) { Settings.Target = NewTarget; })
			+ SSegmentedControl<ESmoothNormalTarget>::Slot(ESmoothNormalTarget::VertexColor)
				.Text(LOCTEXT("VertexColors", "Vertex Colors"))
				.ToolTip(LOCTEXT("VertexColorsTip", "Write the normal into the mesh's vertex color RGB. Exact per vertex, no UV requirements"))
			+ SSegmentedControl<ESmoothNormalTarget>::Slot(ESmoothNormalTarget::Texture)
				.Text(LOCTEXT("Texture", "Texture"))
				.ToolTip(LOCTEXT("TextureTip", "Rasterize the normal into a new texture through a UV channel. Needs UVs that don't overlap or mirror"))),

		// Vertex colors
		OnlyWhen(VertexColorOnly, VrrMenu::Row(LOCTEXT("Alpha", "Alpha"),
			VrrMenu::CheckBox(&Settings.bKeepAlpha, LOCTEXT("KeepAlpha", "Keep existing alpha"),
				LOCTEXT("KeepAlphaTip", "Leave the vertex color alpha as it is (free for an outline thickness mask). Off sets it to 1")),
			FText::GetEmpty(),
			TAttribute<bool>::CreateLambda([this]() { return !Settings.bBakeThicknessMask; }))),

		// Texture
		OnlyWhen(TextureOnly, VrrMenu::Row(LOCTEXT("UVChannel", "UV channel"),
			VrrMenu::UVChannelCombo([this]() { return NumUVChannels; }, &Settings.UVChannel))),
		OnlyWhen(TextureOnly, VrrMenu::Row(LOCTEXT("Resolution", "Resolution"),
			VrrMenu::ResolutionCombo(&Settings.Resolution, { 256, 512, 1024, 2048, 4096 }))),
		OnlyWhen(TextureOnly, VrrMenu::Row(LOCTEXT("Padding", "Padding (px)"),
			VrrMenu::IntField(&Settings.Padding, 0, 32),
			LOCTEXT("PaddingTip", "Grow each UV island by this many pixels so bilinear sampling at the edges doesn't pick up empty texels"))),
		OnlyWhen(TextureOnly, VrrMenu::Row(LOCTEXT("Folder", "Folder"),
			VrrMenu::FolderPicker(&Settings.OutputFolder, TEXT("/Game"), [this](const FText& Error) { SetStatus(Error, true); }))),
		OnlyWhen(TextureOnly, VrrMenu::Row(LOCTEXT("Name", "Name"),
			VrrMenu::NameField(&Settings.OutputName))),
	}));
}

/** Bake button and the status line; the help explains how to use the result in a material. */
TSharedRef<SWidget> SMenu_BakeNormals::CreateBakeSection()
{
	const TAttribute<FText> MaterialHint = TAttribute<FText>::CreateLambda([this]()
	{
		const FText Source = Settings.Target == ESmoothNormalTarget::VertexColor
			? LOCTEXT("SourceVertexColor", "Vertex Color RGB")
			: LOCTEXT("SourceTexture", "the texture, sampled in World Position Offset with Mip Value Mode = Mip Level 0");
		const FText Transform = Settings.Space == ESmoothNormalSpace::Tangent
			? LOCTEXT("TransformTangent", "Transform Vector (Tangent to World)")
			: LOCTEXT("TransformObject", "Transform Vector (Local to World)");
		return FText::Format(LOCTEXT("MaterialHint", "In a material: {0} * 2 - 1, Normalize, then {1}. Use the result as the outline push direction."), Source, Transform);
	});

	return VrrMenu::HelpCard(LOCTEXT("BakeHeader", "Bake"), MaterialHint, VrrMenu::Rows({
		VrrMenu::ActionButton(LOCTEXT("Bake", "Bake Smooth Normals"),
			LOCTEXT("BakeTip", "Bake into the selected output. Vertex color bakes can be undone with Ctrl+Z"),
			[this]() { return GetBakeBlocker(); },
			FOnClicked::CreateSP(this, &SMenu_BakeNormals::OnBakeClicked)),
		VrrMenu::StatusLine(&StatusText, &bStatusIsError),
	}));
}

// BEHAVIOR
/**
 * Switches to a new mesh: resets the per-mesh state and suggests output folder, name and UV channel.
 * Called again with the same mesh after a bake, it only refreshes the info (vertex colors now present),
 * keeping the chosen UV channel and output name.
 */
void SMenu_BakeNormals::SetMesh(UObject* NewMesh)
{
	const bool bNewMesh = NewMesh != Mesh.Get();
	Mesh = VrrCore::IsStaticOrSkeletalMesh(NewMesh) ? NewMesh : nullptr;
	NumUVChannels = 0;
	bMeshHasVertexColors = false;
	StatusText = FText::GetEmpty();

	if (Mesh.IsValid())
	{
		if (IsSkeletal())
		{
			Settings.Space = ESmoothNormalSpace::Tangent;
		}

		NumUVChannels = VrrCore::GetNumUVChannels(Mesh.Get());
		bMeshHasVertexColors = SmoothNormalBaker::HasVertexColors(Mesh.Get());
		if (bNewMesh)
		{
			Settings.OutputFolder = FPackageName::GetLongPackagePath(Mesh->GetOutermost()->GetName());
			Settings.OutputName = SmoothNormalBaker::SuggestTextureName(Mesh.Get());
		}
	}
	if (bNewMesh || Settings.UVChannel >= NumUVChannels)
	{
		Settings.UVChannel = 0;
	}
}

/** Skeletal meshes must use tangent space (object space doesn't follow skinning). */
bool SMenu_BakeNormals::IsSkeletal() const
{
	return VrrCore::IsSkeletalMesh(Mesh.Get());
}

/** Why Bake can't run yet (shown next to the button), or empty when it can. */
FText SMenu_BakeNormals::GetBakeBlocker() const
{
	if (!Mesh.IsValid())
	{
		return LOCTEXT("NeedMesh", "Pick a mesh first.");
	}
	if (!VrrCore::GetMeshDescription(Mesh.Get(), 0))
	{
		return LOCTEXT("NeedMeshData", "This mesh has no editable LOD 0 data.");
	}
	if (Settings.Target == ESmoothNormalTarget::Texture && NumUVChannels == 0)
	{
		return LOCTEXT("NeedUVs", "This mesh has no UVs to bake a texture through.");
	}
	return FText::GetEmpty();
}

/** "Static Mesh | 2 LODs with mesh data | ..." or why the mesh can't be baked. */
FText SMenu_BakeNormals::GetMeshInfoText() const
{
	if (!Mesh.IsValid())
	{
		return LOCTEXT("NoMesh", "Pick a Static Mesh or Skeletal Mesh.");
	}

	const FMeshDescription* MeshDescription = VrrCore::GetMeshDescription(Mesh.Get(), 0);
	if (!MeshDescription)
	{
		return LOCTEXT("NoMeshData", "This mesh has no source mesh data to edit (LOD 0 is missing or generated).");
	}

	return FText::Format(LOCTEXT("MeshInfo", "{0}  |  {1} LODs with mesh data  |  {2} vertices, {3} triangles  |  {4} UV channels  |  {5}"),
		IsSkeletal() ? LOCTEXT("Skeletal", "Skeletal Mesh") : LOCTEXT("Static", "Static Mesh"),
		VrrCore::GetLODsWithMeshData(Mesh.Get()).Num(),
		MeshDescription->Vertices().Num(),
		MeshDescription->Triangles().Num(),
		NumUVChannels,
		bMeshHasVertexColors ? LOCTEXT("HasColors", "has vertex colors") : LOCTEXT("NoColors", "no vertex colors"));
}

/** Confirms overwriting vertex colors if needed, bakes, then reports and refreshes the info line. */
FReply SMenu_BakeNormals::OnBakeClicked()
{
	if (!GetBakeBlocker().IsEmpty())
	{
		return FReply::Handled();
	}

	if (Settings.Target == ESmoothNormalTarget::VertexColor && bMeshHasVertexColors)
	{
		const EAppReturnType::Type Answer = FMessageDialog::Open(EAppMsgType::YesNo,
			FText::Format(LOCTEXT("OverwriteColors", "{0} already has vertex colors. Baking replaces their RGB{1}.\n\nContinue?"),
				FText::FromString(Mesh->GetName()),
				Settings.bBakeThicknessMask ? LOCTEXT("AlphaMask", " and replaces alpha with the thickness mask")
					: Settings.bKeepAlpha ? LOCTEXT("AlphaKept", " (alpha is kept)") : FText::GetEmpty()));
		if (Answer != EAppReturnType::Yes)
		{
			return FReply::Handled();
		}
	}

	const FSmoothNormalBakeResult Result = SmoothNormalBaker::Bake(Mesh.Get(), Settings);

	VrrMenu::Notify(Result.bSuccess ? LOCTEXT("BakeDone", "Smooth normals baked") : Result.Message,
		Result.bSuccess ? VrrMenu::ENotify::Success : VrrMenu::ENotify::Error);
	if (Result.Texture)
	{
		VrrCore::ShowInContentBrowser({ Result.Texture });
	}

	// Refresh the info line (vertex colors now present); the same mesh keeps its settings
	SetMesh(Mesh.Get());
	SetStatus(Result.Message, !Result.bSuccess);
	return FReply::Handled();
}

/** Text (and error color) for the status line under the Bake button. */
void SMenu_BakeNormals::SetStatus(const FText& Text, bool bError)
{
	StatusText = Text;
	bStatusIsError = bError;
}

