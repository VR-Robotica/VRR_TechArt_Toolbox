	int32 GetNumUVChannels(UObject* Mesh);

	// TEXTURE BAKING

	/**
	 * Twice the signed area of triangle ABC (positive or negative depending on winding).
	 * The texture bakers rasterize triangles in UV space with it: for a texel center P,
	 * EdgeFunction(B, C, P) / EdgeFunction(A, B, C) is P's barycentric weight for A (same for B and C).
	 * All three weights >= 0 means P is inside the triangle, and the weights blend the corner values.
	 */
	inline float EdgeFunction(const FVector2f& A, const FVector2f& B, const FVector2f& C)
	{
		return (B.X - A.X) * (C.Y - A.Y) - (B.Y - A.Y) * (C.X - A.X);
	}

	/**
	 * Island padding (dilation), used by every texture baker so filtering and mips at island borders never reach
	 * empty texels. Each pass visits the empty texels that touch a filled one (8 neighbors) and calls
	 * FillTexel(Index, FilledNeighbors), which writes the texel's value (usually the neighbors' average);
	 * the texel counts as filled from the next pass on, so each pass grows the islands by one texel.
	 * Stops after Passes passes or when nothing is left to grow into. Filled is updated.
	 */
	void PadIslands(int32 Size, int32 Passes, TBitArray<>& Filled, TFunctionRef<void(int32 Index, TConstArrayView<int32> FilledNeighbors)> FillTexel);

	/** 0..1 -> 0..255 (clamped, rounded). */
	inline uint8 ToByte01(float Value)
	{
		return static_cast<uint8>(FMath::Clamp(FMath::RoundToInt(Value * 255.0f), 0, 255));
	}
