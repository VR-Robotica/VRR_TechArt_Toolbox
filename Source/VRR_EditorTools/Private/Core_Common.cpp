/*
 * Shared editor helpers for the Toolbox core code (Core_*.cpp).
 *
 * Everything here is small and stateless: content paths, Content Browser access, and reading meshes
 * the same way for Static and Skeletal Meshes. The bakers work on FMeshDescription (the editable source
 * data an asset is built from), so they don't need to care which of the two mesh types they were given.
 */

