	// CONTENT FOLDERS AND ASSETS

	/** "Game/Textures/", "\Game\Textures" -> "/Game/Textures". Empty -> Default. */
	FString NormalizeContentFolder(const FString& Folder, const FString& Default = TEXT("/Game"));

